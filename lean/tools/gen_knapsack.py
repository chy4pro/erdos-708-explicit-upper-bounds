#!/usr/bin/env python3
"""Generate Erdos708/H883/Knapsack.lean: exact certificates for the two knapsacks of
Section 18 (Lemma 18.3 retention prefix budget 480/720 = 2/3; Lemma 18.4 rounding loss
259272/92160 = 3601/1280). A certificate g for items S (cost c, reward r) is a table with
g[w - c(u)] + r(u) <= g[w]; the Lean file checks this by `decide +kernel` and derives the
bound for every list of items by induction. Usage: python3 tools/gen_knapsack.py > Erdos708/H883/Knapsack.lean"""
ETA = {9:60,10:60,11:71,12:72,13:76,14:80,15:88,16:96,18:120,20:120,22:120,24:120,26:120,
       28:120,30:160,32:160,36:240,40:240,44:240,48:240,52:240,56:240,60:240,64:240}
LV = sorted(ETA)
SUCC = {v: (LV[i+1] if i+1 < len(LV) else 64) for i, v in enumerate(LV)}

def table(items, cost, rew, W):
    g = [0]*(W+1)
    for w in range(W+1):
        g[w] = max([0]+[g[w-cost(u)]+rew(u) for u in items if cost(u) <= w])
    return g

ret = {v: table([u for u in LV if u >= v], lambda u: u, ETA.get, 64) for v in LV}
assert all(ret[v][64] + ETA[v] <= 480 for v in LV)
rnd = table(LV, ETA.get, SUCC.get, 719)
assert max(1440*rnd[w] + 243*(720-w) for w in range(720)) == 259272

L = lambda xs: '[' + ','.join(map(str, xs)) + ']'
print(f'''import Mathlib

/-!
Section 18, Lemmas 18.3 and 18.4: the two exact knapsacks (generated by `tools/gen_knapsack.py`).

Large levels `t = v/64 > 1/8` of `𝒟` are recorded by `v ∈ levels`; `E v = 720 η(v/64)` is the
retention exponent of Lemma 18.3 and `succ v` the successor level of `v/64` in `𝒟` (in units of
`1/64`; `64` at the top level `1`), the rounding error bound of Lemma 18.4.

* `retention_knapsack`: for every large level `v` and every multiset `l` of large levels `≥ v`
  of total `≤ 64` (mass `≤ 1`), `∑ E + E v ≤ 480`, i.e. the prefix budget is `≤ 480/720 = 2/3`.
* `rounding_knapsack`: for every multiset `l` of large levels of total cost `w = ∑ E ≤ 719`,
  `1440 ∑ succ + 243 (720 - w) ≤ 259272`, and `259272 / 92160 = 3601/1280 = D₀`.
-/

namespace Erdos708H883.Knapsack

set_option maxRecDepth 100000

/-- The large levels `v/64 > 1/8` of `𝒟 = {{1}} ∪ {{j/2^h : 8 ≤ j ≤ 15, h ≥ 4}}`. -/
def levels : List ℕ := {L(LV)}

/-- `720 η(v/64)` for the large levels (Lemma 18.3). -/
def E (v : ℕ) : ℕ :=
  if v ≤ 10 then 60 else if v = 11 then 71 else if v = 12 then 72 else if v = 13 then 76
  else if v = 14 then 80 else if v = 15 then 88 else if v = 16 then 96 else if v ≤ 28 then 120
  else if v ≤ 32 then 160 else 240

/-- The successor level of `v/64` in `𝒟`, in units of `1/64` (and `64` at the top). -/
def succ (v : ℕ) : ℕ := if v < 16 then v + 1 else if v < 32 then v + 2 else min (v + 4) 64

theorem E_succ_table :
    levels.map E = {L([ETA[v] for v in LV])} ∧ levels.map succ = {L([SUCC[v] for v in LV])} := by
  decide +kernel

/-- `pairLe r xs ys`: `xs[i] + r ≤ ys[i]` at every common index. -/
def pairLe (r : ℕ) : List ℕ → List ℕ → Bool
  | a :: as, b :: bs => decide (a + r ≤ b) && pairLe r as bs
  | _, _ => true

theorem pairLe_spec {{r : ℕ}} : ∀ {{xs ys : List ℕ}}, pairLe r xs ys = true →
    ∀ i, i < xs.length → i < ys.length → xs.getD i 0 + r ≤ ys.getD i 0
  | [], _, _, i, h, _ => by simp at h
  | _ :: _, [], _, i, _, h' => by simp at h'
  | a :: as, b :: bs, h, i, hi, hi' => by
      simp only [pairLe, Bool.and_eq_true, decide_eq_true_eq] at h
      cases i with
      | zero => simpa using h.1
      | succ i =>
          simpa using pairLe_spec h.2 i (by simpa using hi) (by simpa using hi')

/-- `g` certifies items `S` with cost `c` and reward `r`: `g[w - c u] + r u ≤ g[w]`. -/
def certOK (S : List ℕ) (c r : ℕ → ℕ) (g : List ℕ) : Bool :=
  S.all fun u => pairLe (r u) g (g.drop (c u))

theorem knapsack_le {{S : List ℕ}} {{c r : ℕ → ℕ}} {{g : List ℕ}} (hg : certOK S c r g = true) :
    ∀ l : List ℕ, (∀ u ∈ l, u ∈ S) → ∀ w, w < g.length → (l.map c).sum ≤ w →
      (l.map r).sum ≤ g.getD w 0
  | [], _, w, _, _ => by simp
  | u :: l, hl, w, hw, hs => by
      simp only [List.map_cons, List.sum_cons] at hs ⊢
      have hu : u ∈ S := hl u (by simp)
      have hcu : c u ≤ w := le_trans (Nat.le_add_right _ _) hs
      have ih := knapsack_le hg l (fun v hv => hl v (by simp [hv])) (w - c u) (by omega)
        (by omega)
      have hp := (List.all_eq_true.mp hg) u hu
      have hstep := pairLe_spec hp (w - c u) (by omega) (by simp only [List.length_drop]; omega)
      have e : (g.drop (c u)).getD (w - c u) 0 = g.getD w 0 := by
        simp only [List.getD_eq_getElem?_getD, List.getElem?_drop, Nat.add_sub_cancel' hcu]
      omega

/-- Retention certificates, one per large level `v` (items: large levels `≥ v`, cost `u`). -/
def retCerts : List (List ℕ) :=
  [{(','+chr(10)+'   ').join(L(ret[v]) for v in LV)}]

def retCert (v : ℕ) : List ℕ := ((levels.zip retCerts).lookup v).getD []

theorem retCert_ok : levels.all (fun v =>
    certOK (levels.filter (fun u => decide (v ≤ u))) id E (retCert v) &&
      decide (64 < (retCert v).length) && decide ((retCert v).getD 64 0 + E v ≤ 480)) = true := by
  decide +kernel

/-- Lemma 18.3 (exact knapsack): a shortest nonincreasing prefix whose last level is the large
level `v/64` has, after removing that level, mass `∑ l / 64 ≤ 1`, and its retention budget is
`(∑ E + E v)/720 ≤ 480/720 = 2/3`. -/
theorem retention_knapsack (v : ℕ) (hv : v ∈ levels) (l : List ℕ)
    (hl : ∀ u ∈ l, u ∈ levels ∧ v ≤ u) (hs : l.sum ≤ 64) : (l.map E).sum + E v ≤ 480 := by
  have h := (List.all_eq_true.mp retCert_ok) v hv
  simp only [Bool.and_eq_true, decide_eq_true_eq] at h
  obtain ⟨⟨hc, hlen⟩, htop⟩ := h
  have := knapsack_le hc l (fun u hu => by
      simp only [List.mem_filter, decide_eq_true_eq]; exact hl u hu) 64 hlen (by simpa using hs)
  omega

/-- Rounding certificate (items: all large levels, cost `E`, reward `succ`), `w ≤ 719`. -/
def rndCert : List ℕ := {L(rnd)}

/-- `rowOK w₀ g`: `1440 g[i] + 243 (720 - (w₀ + i)) ≤ 259272` at every index `i` of `g`.
(A structural walk; `List.range` with `getD` exhausts the kernel's memory.) -/
def rowOK : ℕ → List ℕ → Bool
  | w, a :: t => decide (1440 * a + 243 * (720 - w) ≤ 259272) && rowOK (w + 1) t
  | _, [] => true

theorem rowOK_spec : ∀ {{g : List ℕ}} {{w₀ : ℕ}}, rowOK w₀ g = true →
    ∀ i, i < g.length → 1440 * g.getD i 0 + 243 * (720 - (w₀ + i)) ≤ 259272
  | [], _, _, i, hi => by simp at hi
  | a :: t, w₀, h, i, hi => by
      simp only [rowOK, Bool.and_eq_true, decide_eq_true_eq] at h
      cases i with
      | zero => simpa using h.1
      | succ i =>
          have h2 := rowOK_spec h.2 i (by simpa using hi)
          rw [show w₀ + (i + 1) = w₀ + 1 + i by omega]
          simpa using h2

theorem rndCert_ok : certOK levels E succ rndCert = true ∧ rndCert.length = 720 ∧
    rowOK 0 rndCert = true := by
  decide +kernel

/-- Lemma 18.4 (exact knapsack): large unretained levels have total cost `w = ∑ E ≤ 719`
(strict inequality `∑ η < 1`, integer costs); the total error `∑ succ / 64` from them plus
`(243/128) (720 - w)/720` from the small levels is at most `259272 / 92160`. -/
theorem rounding_knapsack (l : List ℕ) (hl : ∀ u ∈ l, u ∈ levels) (hs : (l.map E).sum ≤ 719) :
    1440 * (l.map succ).sum + 243 * (720 - (l.map E).sum) ≤ 259272 := by
  obtain ⟨hc, hlen, hrow⟩ := rndCert_ok
  have hR := knapsack_le hc l hl _ (by omega) le_rfl
  have hw := rowOK_spec hrow (l.map E).sum (by omega)
  rw [Nat.zero_add] at hw
  have := Nat.mul_le_mul_left 1440 hR
  omega

theorem budget_eq : ((480 : ℚ) / 720) = 2 / 3 := by norm_num

theorem rounding_eq : ((259272 : ℚ) / 92160) = 3601 / 1280 := by norm_num

/-- The threshold: `c = D₀ + ρ T = 3601/1280 + (9/8)(401/75) = 56501/6400`. -/
theorem threshold_eq : ((3601 : ℚ) / 1280) + 9 / 8 * (401 / 75) = 56501 / 6400 := by norm_num

end Erdos708H883.Knapsack''')
