#!/usr/bin/env python3
"""Generate Erdos708/H883/PrimeDensity.lean: the finite ranges of Lemma 18.6,
  40*pi(v) <= 9v on [210, 32768), 20*pi(v) <= 3v on [2310, 2^17), 8*pi(v) <= v on [30030, 2^21).
One kernel pass (`decide +kernel`, chunks of 4096) walks n < 2^21 keeping a count c: n is either
in the hint list (c+1) or must be < 2 or have a factor p in [2, n) from `smallPrimes`. Hence
c >= pi(n) whatever the hints are, and the density is checked at every n.
Usage: python3 tools/gen_prime_density.py > Erdos708/H883/PrimeDensity.lean"""
N, CH = 2**21, 4096
s = bytearray([1])*N; s[0] = s[1] = 0
for p in range(2, int(N**.5)+1):
    if s[p]: s[p*p::p] = bytearray(len(s[p*p::p]))
small = [p for p in range(2, 1449) if s[p]]
counts, slices, c = [0], [], 0
for i in range(N//CH):
    sl = [n for n in range(i*CH, (i+1)*CH) if s[n]]
    slices.append(sl); c += len(sl); counts.append(c)
L = lambda xs: '[' + ','.join(map(str, xs)) + ']'
NC = N//CH
print(f'''import Mathlib

/-!
Section 18, Lemma 18.6, the finite ranges (generated by `tools/gen_prime_density.py`):
`π(ν)/ν ≤ 9/40` on `[210, 32768)`, `≤ 3/20` on `[2310, 2^17)`, `≤ 1/8` on `[30030, 2^21)`.

`run` walks `n` upward with a running count `c`. A number equal to the head of the hint list is
counted; any other number must be `< 2` or have a divisor `p ∈ smallPrimes` with `2 ≤ p < n`, so
it is not prime. Therefore `c ≥ π(n)` regardless of the hints (`run_spec`), and the three
densities are checked at every `n`. The kernel evaluates the pass in {NC} chunks of {CH}.
-/

namespace Erdos708H883.PrimeDensity

set_option maxRecDepth 100000
set_option maxHeartbeats 0

def smallPrimes : List ℕ := {L(small)}

/-- `n < 2`, or `n` has a divisor `p ∈ smallPrimes` with `2 ≤ p < n`. -/
def hasSmall (n : ℕ) : Bool :=
  decide (n < 2) || smallPrimes.any fun p => decide (2 ≤ p) && decide (p < n) && n % p == 0

theorem not_prime_of_hasSmall {{n : ℕ}} (h : hasSmall n = true) : ¬ n.Prime := by
  intro hp
  have h2 := hp.two_le
  simp only [hasSmall, Bool.or_eq_true, decide_eq_true_eq] at h
  rcases h with h | h
  · omega
  · obtain ⟨p, -, hp2⟩ := List.any_eq_true.mp h
    simp only [Bool.and_eq_true, decide_eq_true_eq, beq_iff_eq] at hp2
    obtain ⟨⟨hp2, hlt⟩, hmod⟩ := hp2
    rcases hp.eq_one_or_self_of_dvd p (Nat.dvd_of_mod_eq_zero hmod) with h1 | h1 <;> omega

/-- The three density statements at `m` for a count `c` of the primes `≤ m`. -/
abbrev densP (m c : ℕ) : Prop :=
  (210 ≤ m → m < 32768 → 40 * c ≤ 9 * m) ∧ (2310 ≤ m → m < 131072 → 20 * c ≤ 3 * m) ∧
    (30030 ≤ m → m < 2097152 → 8 * c ≤ m)

theorem densP_mono {{m c c' : ℕ}} (h : densP m c) (hc : c' ≤ c) : densP m c' := by
  obtain ⟨h1, h2, h3⟩ := h
  exact ⟨fun a b => by have := h1 a b; omega, fun a b => by have := h2 a b; omega,
    fun a b => by have := h3 a b; omega⟩

def run : ℕ → ℕ → ℕ → List ℕ → Option ℕ
  | _, 0, c, _ => some c
  | n, k + 1, c, a :: t =>
      if a = n then (if decide (densP n (c + 1)) then run (n + 1) k (c + 1) t else none)
      else if (hasSmall n && decide (densP n c)) = true then run (n + 1) k c (a :: t) else none
  | n, k + 1, c, [] =>
      if (hasSmall n && decide (densP n c)) = true then run (n + 1) k c [] else none

theorem run_zero (n c : ℕ) (L : List ℕ) : run n 0 c L = some c := by
  cases L <;> rfl

theorem run_cons (n k c a : ℕ) (t : List ℕ) : run n (k + 1) c (a :: t) =
    if a = n then (if decide (densP n (c + 1)) then run (n + 1) k (c + 1) t else none)
    else if (hasSmall n && decide (densP n c)) = true then run (n + 1) k c (a :: t) else none :=
  rfl

theorem run_nil (n k c : ℕ) : run n (k + 1) c [] =
    if (hasSmall n && decide (densP n c)) = true then run (n + 1) k c [] else none :=
  rfl

theorem step_nonprime {{n c : ℕ}} (hs : (hasSmall n && decide (densP n c)) = true)
    (hc : Nat.count Nat.Prime n ≤ c) : Nat.count Nat.Prime (n + 1) ≤ c ∧ densP n c := by
  simp only [Bool.and_eq_true, decide_eq_true_eq] at hs
  refine ⟨?_, hs.2⟩
  rw [Nat.count_succ, if_neg (not_prime_of_hasSmall hs.1)]
  omega

theorem run_spec : ∀ (k n c : ℕ) (L : List ℕ) (c' : ℕ), run n k c L = some c' →
    Nat.count Nat.Prime n ≤ c →
    Nat.count Nat.Prime (n + k) ≤ c' ∧
      ∀ m, n ≤ m → m < n + k → densP m (Nat.count Nat.Prime (m + 1))
  | 0, n, c, L, c', h, hc => by
      rw [run_zero, Option.some.injEq] at h
      subst h
      exact ⟨by simpa using hc, fun m h1 h2 => absurd h2 (by omega)⟩
  | k + 1, n, c, L, c', h, hc => by
      have hstep : ∃ c₁ L₁, run (n + 1) k c₁ L₁ = some c' ∧
          Nat.count Nat.Prime (n + 1) ≤ c₁ ∧ densP n c₁ := by
        cases L with
        | nil =>
            rw [run_nil] at h
            by_cases hs : (hasSmall n && decide (densP n c)) = true
            · rw [if_pos hs] at h
              exact ⟨c, [], h, step_nonprime hs hc⟩
            · rw [if_neg hs] at h
              simp at h
        | cons a t =>
            rw [run_cons] at h
            by_cases ha : a = n
            · rw [if_pos ha] at h
              by_cases hd : densP n (c + 1)
              · rw [if_pos (decide_eq_true hd)] at h
                refine ⟨c + 1, t, h, ?_, hd⟩
                rw [Nat.count_succ]
                split_ifs <;> omega
              · rw [if_neg (by simpa using hd)] at h
                simp at h
            · rw [if_neg ha] at h
              by_cases hs : (hasSmall n && decide (densP n c)) = true
              · rw [if_pos hs] at h
                exact ⟨c, a :: t, h, step_nonprime hs hc⟩
              · rw [if_neg hs] at h
                simp at h
      obtain ⟨c₁, L₁, hrun, hc₁, hd⟩ := hstep
      obtain ⟨ih1, ih2⟩ := run_spec k (n + 1) c₁ L₁ c' hrun hc₁
      refine ⟨by rwa [show n + (k + 1) = n + 1 + k by omega], fun m h1 h2 => ?_⟩
      rcases Nat.eq_or_lt_of_le h1 with rfl | hlt
      · exact densP_mono hd hc₁
      · exact ih2 m (by omega) (by omega)

/-- `counts[i]` = number of primes below `{CH} i` (any upper bound would do). -/
def counts : List ℕ := {L(counts)}

/-- Hint lists: the primes in `[{CH} i, {CH} (i+1))`. -/
def slices : List (List ℕ) :=
  [{(','+chr(10)+'   ').join(L(x) for x in slices)}]

theorem chunks_ok : (List.range {NC}).all (fun i =>
    decide (run ({CH} * i) {CH} (counts.getD i 0) (slices.getD i []) = some (counts.getD (i + 1) 0)))
      = true := by
  decide +kernel

theorem count_le : ∀ i, i ≤ {NC} → Nat.count Nat.Prime ({CH} * i) ≤ counts.getD i 0 := by
  intro i
  induction i with
  | zero => intro _; simp
  | succ i ih =>
      intro hi
      have h := of_decide_eq_true ((List.all_eq_true.mp chunks_ok) i (List.mem_range.mpr (by omega)))
      have := (run_spec {CH} ({CH} * i) _ _ _ h (ih (by omega))).1
      rwa [show {CH} * i + {CH} = {CH} * (i + 1) by ring] at this

theorem dens_all (m : ℕ) (hm : m < {N}) : densP m (Nat.count Nat.Prime (m + 1)) := by
  have hi : m / {CH} < {NC} := by omega
  have h := of_decide_eq_true ((List.all_eq_true.mp chunks_ok) (m / {CH}) (List.mem_range.mpr hi))
  exact (run_spec {CH} ({CH} * (m / {CH})) _ _ _ h (count_le _ hi.le)).2 m (by omega) (by omega)

theorem primeCounting_eq (m : ℕ) : Nat.primeCounting m = Nat.count Nat.Prime (m + 1) := rfl

/-- Lemma 18.6, `π(ν)/ν ≤ 9/40` for `210 ≤ ν < 32768`. -/
theorem density_9_40 (ν : ℕ) (h1 : 210 ≤ ν) (h2 : ν < 32768) : 40 * Nat.primeCounting ν ≤ 9 * ν := by
  rw [primeCounting_eq]; exact (dens_all ν (by omega)).1 h1 h2

/-- Lemma 18.6, `π(ν)/ν ≤ 3/20` for `2310 ≤ ν < 2^17`. -/
theorem density_3_20 (ν : ℕ) (h1 : 2310 ≤ ν) (h2 : ν < 131072) : 20 * Nat.primeCounting ν ≤ 3 * ν := by
  rw [primeCounting_eq]; exact (dens_all ν (by omega)).2.1 h1 h2

/-- Lemma 18.6, `π(ν)/ν ≤ 1/8` for `30030 ≤ ν < 2^21`. -/
theorem density_1_8 (ν : ℕ) (h1 : 30030 ≤ ν) (h2 : ν < 2097152) : 8 * Nat.primeCounting ν ≤ ν := by
  rw [primeCounting_eq]; exact (dens_all ν (by omega)).2.2 h1 h2

end Erdos708H883.PrimeDensity''')
