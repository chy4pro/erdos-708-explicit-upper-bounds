"""Generate Erdos708/H883/Knapsack.lean: exact certificates for the two knapsacks of
Lemmas 18.3 (retention budget 480/720) and 18.4 (rounding loss 3601/1280) of paper/sec_h883.tex.
Each certificate is a table g with g(w-c_u)+gain_u <= g(w); Lean checks it by `decide`."""
import sys
E = {9:60,10:60,11:71,12:72,13:76,14:80,15:88,16:96}
E.update({u:120 for u in range(18,29,2)}); E.update({30:160,32:160})
E.update({u:240 for u in range(36,65,4)})
V = sorted(E); assert len(V) == 24
succ = {v:(V[i+1] if i+1 < len(V) else 64) for i,v in enumerate(V)}
def best(items, W):  # g[w] = max gain over multisets with total cost <= w
    g = [0]*(W+1)
    for w in range(W+1):
        g[w] = max([g[w-1]] if w else [0])
        for c,r in items:
            if c <= w: g[w] = max(g[w], g[w-c]+r)
    return g
ret = {}
for v in V:
    g = best([(u,E[u]) for u in V if u >= v], 64)
    assert g[64]+E[v] == 480, (v, g[64]+E[v]); ret[v] = g
h = best([(E[v],succ[v]) for v in V], 719)
val = max(1440*h[w]+243*(720-w) for w in range(720)); assert val == 259272
L = []
L.append("""import Mathlib

/-!
Section 18 (paper/sec_h883.tex), the two exact knapsacks. Generated by
`lean/tools/gen_h883_knapsack.py`; do not edit by hand.

Levels above 1/8 are written `v/64` with `v ∈ V` (24 values, 9 ≤ v ≤ 64); `E v = 720·η(v/64)`
and `succ v` is the next level of the eight-mantissa set (64 at the top).

* `retention_budget` (Lemma 18.3): a multiset of levels `≥ v` of total mass `≤ 64/64`
  together with the level `v` has total `720·η ≤ 480`.
* `rounding_budget` (Lemma 18.4): large levels of total cost `w = Σ E ≤ 719` have
  `1440·Σ succ + 243·(720 - w) ≤ 259272`, and `259272/92160 = 3601/1280`.
-/

namespace Erdos708H883.Knapsack

def V : List ℕ := %s

def E (v : ℕ) : ℕ :=
  if v ≤ 10 then 60 else if v = 11 then 71 else if v = 12 then 72 else if v = 13 then 76
  else if v = 14 then 80 else if v = 15 then 88 else if v = 16 then 96
  else if v ≤ 28 then 120 else if v ≤ 32 then 160 else 240

def succ (v : ℕ) : ℕ :=
  if v < 16 then v + 1 else if v < 32 then v + 2 else if v < 64 then v + 4 else 64

theorem E_table : V.map E = %s := by decide
theorem succ_table : V.map succ = %s := by decide
""" % (V, [E[v] for v in V], [succ[v] for v in V]))
L.append("/-- Retention certificates: `retTable v` lists `g_v(0), …, g_v(64)`. -/")
L.append("def retTable (v : ℕ) : List ℕ :=")
for i,v in enumerate(V):
    L.append(f"  {'if' if i==0 else 'else if'} v = {v} then {ret[v]}")
L.append("  else []\n")
L.append(f"def rndTable : List ℕ := {h}\n")
L.append("""/-- Certificate check for one retention table. -/
def retOK (v : ℕ) : Bool :=
  (retTable v).length = 65 &&
  (List.range 65).all (fun w => V.all (fun u =>
    !(v ≤ u && u ≤ w) || decide ((retTable v).getD (w - u) 0 + E u ≤ (retTable v).getD w 0))) &&
  decide ((retTable v).getD 64 0 + E v ≤ 480)

def rndOK : Bool :=
  rndTable.length = 720 &&
  (List.range 720).all (fun w => V.all (fun u =>
    !(E u ≤ w) || decide (rndTable.getD (w - E u) 0 + succ u ≤ rndTable.getD w 0))) &&
  (List.range 720).all (fun w => decide (1440 * rndTable.getD w 0 + 243 * (720 - w) ≤ 259272))
""")
for v in V:
    L.append(f"theorem retOK_{v} : retOK {v} = true := by decide")
L.append("theorem rndOK_true : rndOK = true := by decide\n")
L.append("""theorem retOK_all : ∀ v ∈ V, retOK v = true := by
  intro v hv
  simp only [V, List.mem_cons, List.not_mem_nil, or_false] at hv
  rcases hv with """ + " | ".join("rfl" for _ in V) + """
  all_goals first | exact retOK_""" + "| exact retOK_".join(f"{v} " for v in V).rstrip() + """

theorem ret_bound (v : ℕ) (hv : retOK v = true) :
    ∀ (l : List ℕ) (w : ℕ), w ≤ 64 → (∀ u ∈ l, u ∈ V ∧ v ≤ u) → l.sum ≤ w →
      (l.map E).sum ≤ (retTable v).getD w 0 := by
  simp only [retOK, Bool.and_eq_true, decide_eq_true_eq, List.all_eq_true, List.mem_range,
    Bool.or_eq_true, Bool.not_eq_true', Bool.and_eq_false_iff, decide_eq_false_iff_not] at hv
  obtain ⟨⟨_, hstep⟩, _⟩ := hv
  intro l
  induction l with
  | nil => intro w _ _ _; simp
  | cons u l ih =>
    intro w hw hl hs
    have hu := hl u (by simp)
    simp only [List.sum_cons] at hs
    have hle : u ≤ w := by omega
    have h1 := ih (w - u) (by omega) (fun x hx => hl x (by simp [hx])) (by omega)
    have h2 := hstep w (by omega) u hu.1
    simp only [List.map_cons, List.sum_cons]
    rcases h2 with h2 | h2
    · omega
    · omega

/-- Lemma 18.3, exact knapsack: `720·(budget) ≤ 480` for every admissible prefix. -/
theorem retention_budget (v : ℕ) (hv : v ∈ V) (l : List ℕ)
    (hl : ∀ u ∈ l, u ∈ V ∧ v ≤ u) (hs : l.sum ≤ 64) :
    (l.map E).sum + E v ≤ 480 := by
  have hok := retOK_all v hv
  have h := ret_bound v hok l 64 le_rfl hl hs
  simp only [retOK, Bool.and_eq_true, decide_eq_true_eq] at hok
  omega

theorem rnd_bound :
    ∀ (l : List ℕ) (w : ℕ), w < 720 → (∀ u ∈ l, u ∈ V) → (l.map E).sum ≤ w →
      (l.map succ).sum ≤ rndTable.getD w 0 := by
  have hv := rndOK_true
  simp only [rndOK, Bool.and_eq_true, decide_eq_true_eq, List.all_eq_true, List.mem_range,
    Bool.or_eq_true, Bool.not_eq_true', decide_eq_false_iff_not] at hv
  obtain ⟨⟨_, hstep⟩, _⟩ := hv
  intro l
  induction l with
  | nil => intro w _ _ _; simp
  | cons u l ih =>
    intro w hw hl hs
    have hu := hl u (by simp)
    simp only [List.map_cons, List.sum_cons] at hs ⊢
    have h1 := ih (w - E u) (by omega) (fun x hx => hl x (by simp [hx])) (by omega)
    have h2 := hstep w hw u hu
    rcases h2 with h2 | h2
    · omega
    · omega

/-- Lemma 18.4, exact knapsack: large levels of total cost `w ≤ 719` lose at most
`(1440·Σ succ + 243·(720 - w))/92160 ≤ 259272/92160 = 3601/1280`. -/
theorem rounding_budget (l : List ℕ) (hl : ∀ u ∈ l, u ∈ V) (hw : (l.map E).sum ≤ 719) :
    1440 * (l.map succ).sum + 243 * (720 - (l.map E).sum) ≤ 259272 := by
  have h := rnd_bound l _ (by omega) hl le_rfl
  have hv := rndOK_true
  simp only [rndOK, Bool.and_eq_true, decide_eq_true_eq, List.all_eq_true, List.mem_range] at hv
  have h3 := hv.2 _ (by omega : (l.map E).sum < 720)
  omega

theorem rounding_constant : (259272 : ℚ) / 92160 = 3601 / 1280 := by norm_num

/-- `c = D0 + ρ·T` with `D0 = 3601/1280`, `ρ = 9/8`, `T = 401/75`. -/
theorem threshold_identity : (3601 : ℚ) / 1280 + 9 / 8 * (401 / 75) = 56501 / 6400 := by norm_num

end Erdos708H883.Knapsack""")
open(sys.argv[1],'w').write("\n".join(L)+"\n")
